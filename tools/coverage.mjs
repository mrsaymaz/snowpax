#!/usr/bin/env node
// Writes content/COVERAGE.md: for each unit, which sub-tasks can fill each arena, using the
// same task generators the game uses (src/tasks/subtasks.mjs).
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { FAMILIES, SUBTASKS, subtasksOf, statusOf, needFor, usableSubtasks } from '../src/tasks/subtasks.mjs';
import { CONFIG } from '../src/config.js';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const grades = [5, 6, 7, 8].map(g => JSON.parse(readFileSync(join(ROOT, 'content', `grade${g}.json`), 'utf8')));
const log = JSON.parse(readFileSync(join(ROOT, 'content', 'IMPORT-LOG.json'), 'utf8'));
const ICON = { good: '●', ok: '◐', thin: '○', none: '✕', locked: '·' };
const ARENAS = [1, 2, 3];

const lines = [];
const P = s => lines.push(s);
P('# Content coverage');
P('');
P(`Generated by \`npm run coverage\` from \`content/grade5…8.json\` (imported ${grades[0].imported}). Do not edit by hand.`);
P('');
P('Every outpost visit uses one sub-task from its family for all its rounds. Items needed for one visit');
P(`(seize + defend, 3 items a round): Arena 1 = ${needFor(1)}, Arena 2 = ${needFor(2)}, Arena 3 = ${needFor(3)}.`);
P('');
P(`Key: ${ICON.good} good (enough for two visits, stays fresh) · ${ICON.ok} ok (one full visit) · ${ICON.thin} thin (items would repeat inside a visit) · ${ICON.none} cannot fill · ${ICON.locked} not used at this arena`);
P('');
P('A family is **covered** at an arena when at least one of its sub-tasks is ok or good there.');
P('');

// ---------- summary ----------
const problems = [];
const unitRows = [];
for (const g of grades) for (const u of g.units) {
  const row = { u, fam: {} };
  for (const f of FAMILIES) {
    row.fam[f.id] = ARENAS.map(a => {
      const st = subtasksOf(f.id).map(s => statusOf(s, u, a).status);
      return st.some(s => s === 'good') ? 'good' : st.some(s => s === 'ok') ? 'ok' : st.some(s => s === 'thin') ? 'thin' : 'none';
    });
    ARENAS.forEach((a, i) => { if (row.fam[f.id][i] === 'none' || row.fam[f.id][i] === 'thin') problems.push({ u, f, a, s: row.fam[f.id][i] }); });
  }
  row.playable = ARENAS.map((a, i) => FAMILIES.every(f => row.fam[f.id][i] === 'good' || row.fam[f.id][i] === 'ok'));
  unitRows.push(row);
}

P('## Summary: families per unit and arena');
P('');
P('Each cell shows Arena 1 · 2 · 3. A unit is fully playable when every family is covered in all three arenas.');
P('');
P(`| Unit | Title | ${FAMILIES.map(f => `${f.letter} ${f.name}`).join(' | ')} | Playable |`);
P(`|---|---|${FAMILIES.map(() => ':-:').join('|')}|:-:|`);
for (const r of unitRows) {
  P(`| ${r.u.id} | ${r.u.title} | ${FAMILIES.map(f => r.fam[f.id].map(s => ICON[s]).join(' ')).join(' | ')} | ${r.playable.every(Boolean) ? 'yes' : r.playable.map((p, i) => (p ? `A${i + 1}` : '')).filter(Boolean).join(', ') || 'no'} |`);
}
P('');
const full = unitRows.filter(r => r.playable.every(Boolean)).length;
P(`**${full} of ${unitRows.length} units** are covered in every family in all three arenas.`);
P('');

if (problems.length) {
  P('### Gaps');
  P('');
  P('| Unit | Arena | Family | State | What runs instead |');
  P('|---|:-:|---|---|---|');
  for (const p of problems) {
    const subs = usableSubtasks(p.u, p.f.id, p.a);
    P(`| ${p.u.id} ${p.u.title} | ${p.a} | ${p.f.name} | ${p.s === 'none' ? 'cannot fill' : 'thin'} | ${subs.length ? subs.map(s => `${s.id} (items repeat)`).join(', ') : '**nothing: outpost cannot run**'} |`);
  }
  P('');
}

// ---------- sub-task totals ----------
P('## Sub-tasks: how many units can use each one');
P('');
P('| Sub-task | Family | From arena | Units ok or good (A1 / A2 / A3) | Needs |');
P('|---|---|:-:|:-:|---|');
const NEEDS = {
  A1: 'words with Turkish', A2: 'words with a licensed picture', A3: 'word definitions or clues', A4: 'units with numbers (numberProfile)',
  A5: 'sentence halves with reviewed wrong endings', A6: 'questions with short answers', A7: 'short sentences with Turkish (+ speech)',
  B8: 'clues with reviewed options', B9: 'halves with 2 wrong endings', B10: 'grammar gaps', B11: 'questions with reviewed replies',
  B12: 'gaps with Turkish meaning', B13: 'reading contexts', B14: 'sentences with Turkish', C15: 'non-overlapping categories',
  C16: 'categories with non-members', C17: 'misspellings (generated)', C18: 'repairs (broken word)', D19: 'sentences with block boundaries',
  D20: 'single words 3–10 letters', E21: 'words (+ speech)', E22: 'words (+ speech)', E23: 'words',
};
for (const s of SUBTASKS) {
  const counts = ARENAS.map(a => (a < s.minArena ? '·' : unitRows.filter(r => ['ok', 'good'].includes(statusOf(s, r.u, a).status)).length));
  P(`| ${s.id} ${s.title} | ${FAMILIES.find(f => f.id === s.family).name} | ${s.minArena} | ${counts.join(' / ')} | ${NEEDS[s.id]} |`);
}
P('');

// ---------- details per unit ----------
P('## Details per unit');
P('');
P('Numbers are usable items (capacity) for each arena; the symbol is the state.');
P('');
for (const g of grades) {
  P(`### Grade ${g.grade}`);
  P('');
  for (const u of g.units) {
    P(`<details><summary><b>${u.id} ${u.title}</b> (${u.cefr || '—'}): ${u.words.length} words, ${u.sentences.length} sentences, ${u.questions.length} questions, ${u.contexts.length} contexts, ${u.categories.length} categories${u.numbers ? `, numbers ${u.numbers.min}–${u.numbers.max}` : ''}</summary>`);
    P('');
    P('| Sub-task | Arena 1 | Arena 2 | Arena 3 |');
    P('|---|:-:|:-:|:-:|');
    for (const s of SUBTASKS) P(`| ${s.id} ${s.title} | ${ARENAS.map(a => { const r = statusOf(s, u, a); return r.status === 'locked' ? '·' : `${ICON[r.status]} ${r.cap}`; }).join(' | ')} |`);
    const b = [3, 4, 5, 6].map(n => u.sentences.filter(x => x.blocks.length === n).length);
    P('');
    P(`Sentence blocks: ${b.map((c, i) => `${i + 3} blocks: ${c}`).join(', ')}. Sled-run words (A1 ${CONFIG.sled.wordLength[0].join('–')}, A2 ${CONFIG.sled.wordLength[1].join('–')}, A3 ${CONFIG.sled.wordLength[2].join('–')} letters): ${CONFIG.sled.wordLength.map(([lo, hi]) => u.words.filter(w => /^[a-z]+$/.test(w.en) && w.en.length >= lo && w.en.length <= hi).length).join(' / ')}.`);
    P('');
    P('</details>');
    P('');
  }
}

// ---------- suggestions ----------
P('## Suggestions for new content (not written; for Mr. Saymaz to decide)');
P('');
const four = unitRows.filter(r => r.u.sentences.filter(x => x.blocks.length === 4).length < needFor(2)).length;
P(`- **4-block sentences (Builder, Arena 2):** ${four} of ${unitRows.length} units have fewer than ${needFor(2)}. Until more exist, Arena 2 Builder mixes in 3-block sentences or uses Spell the word.`);
const five = unitRows.filter(r => r.u.sentences.filter(x => x.blocks.length >= 5).length < needFor(3)).length;
P(`- **5–6-block sentences (Builder, Arena 3):** ${five} units have too few; Arena 3 builds two shorter sentences in a row instead (allowed by the brief).`);
const noPic = unitRows.filter(r => statusOf(SUBTASKS.find(s => s.id === 'A2'), r.u, 1).status === 'none').map(r => r.u.id);
P(`- **Pictures:** ${noPic.length} units have fewer than 3 picture words (${noPic.join(', ') || 'none'}). Word ↔ picture is skipped there; English ↔ Turkish runs instead.`);
const noCtx = unitRows.filter(r => !r.u.contexts.length).map(r => r.u.id);
P(`- **Reading contexts (Read and answer, Arena 3):** missing in ${noCtx.join(', ') || 'none'}.`);
const thinUnits = unitRows.filter(r => !r.playable.every(Boolean)).map(r => r.u.id);
P(`- **Thin units:** ${thinUnits.join(', ') || 'none'}. These are the smaller enrichment units; the gaps table above shows exactly which outposts would repeat items.`);
P('- **Misspellings** are generated (Growbloom style) and must not be real words in any bank, British/American variants, or rude words. Full list below for review.');
P('- **Sentence halves boards** only combine halves where each pairing is a reviewed wrong ending in at least one direction. Please spot-check a few boards in the preview.');
P('');

// ---------- import log ----------
P('## Import log');
P('');
P('Sources (read-only, at these commits):');
P('');
for (const s of log.sources) P(`- \`${s.repo}\` \`${s.file}\` @ ${s.commit.slice(0, 7)}`);
P('');
P(`- Excluded for length or missing data: ${log.excluded.length}`);
for (const e of log.excluded) P(`  - ${e.unit} ${e.type} \`${e.id}\`: ${e.why}`);
P(`- Words added from Tower Swarm translations: ${log.added.map(a => `${a.unit} "${a.text}"`).join(', ') || 'none'}`);
P(`- Sentence blocks replaced by Languini's reviewed boundaries: ${log.blockFixes.map(b => `\`${b.id}\` (${b.to.join(' · ')})`).join(', ') || 'none'}`);
P('');
P(`<details><summary>Generated misspellings (${log.misspellings.length})</summary>`);
P('');
let cur = '';
for (const m of log.misspellings) { if (m.unit !== cur) { cur = m.unit; P(''); P(`**${cur}:** `); } lines[lines.length - 1] += `${m.word} → ${m.wrong}; `; }
P('');
P('</details>');
P('');

writeFileSync(join(ROOT, 'content', 'COVERAGE.md'), lines.join('\n'));
console.log(`Wrote content/COVERAGE.md: ${full}/${unitRows.length} units covered everywhere; ${problems.length} family gaps.`);
